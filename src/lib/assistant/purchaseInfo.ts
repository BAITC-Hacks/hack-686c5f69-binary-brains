export function getPurchaseInfoAnswer(message: string): string | null {
  const normalized = message.toLowerCase();

  if (/(оплат|касс|счет|счёт|безнал|карта)/i.test(normalized)) {
    return "Оплата возможна по условиям ekt.kz: для точного способа оплаты и счета лучше подтвердить заказ при оформлении. Я не принимаю и не храню платежные данные в чате.";
  }

  if (/(достав|самовывоз|курьер|город|адрес)/i.test(normalized)) {
    return "Условия доставки зависят от города, склада и состава заказа. Напишите город доставки, и я помогу подготовить позиции для оформления.";
  }

  if (/(минимальн|партия|количеств|штук|упаков)/i.test(normalized)) {
    return "Минимальная партия зависит от конкретного товара и упаковки. Укажите артикул или название товара, я проверю это по карточке товара.";
  }

  return null;
}
